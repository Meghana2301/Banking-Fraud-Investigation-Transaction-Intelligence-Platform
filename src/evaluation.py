"""Evaluate rule-based fraud flags against synthetic labels.

Run: python -m src.evaluation
Synthetic labels are generated by the simulator and are NOT real-world fraud ground truth.
"""
import argparse
import json
import sqlite3
from pathlib import Path
from src.pipeline import ROOT
from contextlib import closing


def metrics(rows, threshold=65):
    """rows: iterable of (risk_score, is_fraud, amount)."""
    tp = fp = tn = fn = 0
    flagged_amount = 0.0
    for score, label, amount in rows:
        prediction = int(score >= threshold)
        if prediction:
            flagged_amount += float(amount)
        if prediction and label:
            tp += 1
        elif prediction and not label:
            fp += 1
        elif not prediction and label:
            fn += 1
        else:
            tn += 1
    safe_div = lambda a, b: a / b if b else 0.0
    return {
        "threshold": threshold,
        "true_positives": tp,
        "false_positives": fp,
        "true_negatives": tn,
        "false_negatives": fn,
        "precision": round(safe_div(tp, tp + fp), 4),
        "recall": round(safe_div(tp, tp + fn), 4),
        "false_positive_rate": round(safe_div(fp, fp + tn), 4),
        "review_queue_size": tp + fp,
        "flagged_transaction_value": round(flagged_amount, 2),
    }


def evaluate(db_path=None, thresholds=(30, 50, 65, 80)):
    path = Path(db_path or ROOT / "data" / "banking.db")
    with closing(sqlite3.connect(path)) as conn:
        with conn:
            rows = conn.execute("SELECT risk_score, is_fraud, amount FROM transactions").fetchall()
    return [metrics(rows, threshold) for threshold in thresholds]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--db", default=str(ROOT / "data" / "banking.db"))
    args = parser.parse_args()
    print(json.dumps(evaluate(args.db), indent=2))


if __name__ == "__main__":
    main()
