SELECT
    CUSTOMER_ID,
    COUNT(*) AS TOTAL_TRANSACTIONS,
    COUNT(DISTINCT ACCOUNT_ID) AS TOTAL_ACCOUNTS,
    ROUND(SUM(AMOUNT), 2) AS TOTAL_TRANSACTION_AMOUNT,
    ROUND(AVG(AMOUNT), 2) AS AVG_TRANSACTION_AMOUNT,

    SUM(CASE WHEN FLAGGED = 1 THEN 1 ELSE 0 END)
        AS FLAGGED_TRANSACTIONS,

    SUM(CASE WHEN IS_FRAUD = 1 THEN 1 ELSE 0 END)
        AS LABELED_FRAUD_TRANSACTIONS,

    MAX(RISK_SCORE) AS MAX_RISK_SCORE,
    ROUND(AVG(RISK_SCORE), 2) AS AVG_RISK_SCORE,

    MIN(TRANSACTION_DATE) AS FIRST_TRANSACTION_DATE,
    MAX(TRANSACTION_DATE) AS LAST_TRANSACTION_DATE,

    CASE
        WHEN MAX(RISK_SCORE) >= 80 THEN 'CRITICAL'
        WHEN MAX(RISK_SCORE) >= 65 THEN 'HIGH'
        WHEN MAX(RISK_SCORE) >= 40 THEN 'MEDIUM'
        ELSE 'LOW'
    END AS CUSTOMER_RISK_LEVEL

FROM {{ ref('stg_transactions') }}

GROUP BY CUSTOMER_ID
